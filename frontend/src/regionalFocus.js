function pointInRing(longitude, latitude, ring) {
  let inside = false;

  for (
    let index = 0, previous = ring.length - 1;
    index < ring.length;
    previous = index, index += 1
  ) {
    const [x1, y1] = ring[index];
    const [x2, y2] = ring[previous];

    const intersects =
      ((y1 > latitude) !== (y2 > latitude))
      && (
        longitude
        < ((x2 - x1) * (latitude - y1)) / (y2 - y1) + x1
      );

    if (intersects) {
      inside = !inside;
    }
  }

  return inside;
}

export function isInsideRegionalFocus(
  longitude,
  latitude,
  distanceKm = 500,
) {
  const band = REGIONAL_FADE_BANDS.find(
    (candidate) => candidate.distanceKm === distanceKm,
  );

  if (!band) {
    return false;
  }

  return pointInRing(
    Number(longitude),
    Number(latitude),
    band.ring,
  );
}

export function regionalFocusFeatureCollection() {
  return {
    type: 'FeatureCollection',
    features: REGIONAL_FADE_BANDS.map((band) => ({
      type: 'Feature',
      properties: {
        distance_km: band.distanceKm,
        opacity: band.opacity,
      },
      geometry: {
        type: 'Polygon',
        coordinates: [
          WORLD_RING,
          band.ring,
        ],
      },
    })),
  };
}

export function installRegionalFocus(map) {
  if (map.getSource('regional-focus-mask')) {
    return;
  }

  map.addSource('regional-focus-mask', {
    type: 'geojson',
    data: regionalFocusFeatureCollection(),
  });

  map.addLayer({
    id: 'regional-focus-mask',
    type: 'fill',
    source: 'regional-focus-mask',
    paint: {
      'fill-color': '#031018',
      'fill-opacity': ['get', 'opacity'],
    },
  });
}
